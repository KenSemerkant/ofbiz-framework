#!/usr/bin/env bash

# P3-GATE: extend the RUNNING monolith-db stand-in with the product +
# shipment slices (init.sql in monolith-db.yaml only runs on first volume
# init). Idempotent — safe to re-run. Same DDL/seed as monolith-db.yaml.
# FROM_DATE/PRICE/QUANTITY are TEXT: the Debezium JSON wire form
# (decimal.handling.mode=string, epoch dates) round-trips byte-faithful
# through the product/inventory projections.
set -euo pipefail
NS="ofbiz"

psql_file() {
  kubectl -n "${NS}" exec -i deploy/monolith-db -- psql -U ofbiz -d ofbiz -v ON_ERROR_STOP=1
}

echo "==> [1/3] product slice DDL"
psql_file <<'SQL'
CREATE TABLE IF NOT EXISTS "PRODUCT" (
  "PRODUCT_ID" VARCHAR(20) PRIMARY KEY,
  "PRODUCT_TYPE_ID" VARCHAR(20),
  "INTERNAL_NAME" VARCHAR(255),
  "PRODUCT_NAME" VARCHAR(255),
  "LAST_UPDATED_STAMP" TIMESTAMP
);
CREATE TABLE IF NOT EXISTS "PRODUCT_CATEGORY" (
  "PRODUCT_CATEGORY_ID" VARCHAR(20) PRIMARY KEY,
  "CATEGORY_NAME" VARCHAR(100)
);
CREATE TABLE IF NOT EXISTS "PRODUCT_CATEGORY_MEMBER" (
  "PRODUCT_ID" VARCHAR(20) NOT NULL,
  "PRODUCT_CATEGORY_ID" VARCHAR(20) NOT NULL,
  "FROM_DATE" TEXT,
  PRIMARY KEY ("PRODUCT_ID", "PRODUCT_CATEGORY_ID")
);
CREATE TABLE IF NOT EXISTS "PRODUCT_PRICE" (
  "PRODUCT_ID" VARCHAR(20) NOT NULL,
  "PRODUCT_PRICE_TYPE_ID" VARCHAR(20) NOT NULL,
  "CURRENCY_UOM_ID" VARCHAR(20) NOT NULL,
  "FROM_DATE" TEXT NOT NULL,
  "PRICE" TEXT,
  PRIMARY KEY ("PRODUCT_ID", "PRODUCT_PRICE_TYPE_ID", "CURRENCY_UOM_ID", "FROM_DATE")
);
CREATE TABLE IF NOT EXISTS "PRODUCT_ASSOC" (
  "PRODUCT_ID" VARCHAR(20) NOT NULL,
  "PRODUCT_ID_TO" VARCHAR(20) NOT NULL,
  "PRODUCT_ASSOC_TYPE_ID" VARCHAR(20) NOT NULL,
  "FROM_DATE" TEXT NOT NULL,
  PRIMARY KEY ("PRODUCT_ID", "PRODUCT_ID_TO", "PRODUCT_ASSOC_TYPE_ID", "FROM_DATE")
);
SQL

echo "==> [2/3] shipment slice DDL"
psql_file <<'SQL'
CREATE TABLE IF NOT EXISTS "SHIPMENT" (
  "SHIPMENT_ID" VARCHAR(20) PRIMARY KEY,
  "STATUS_ID" VARCHAR(30),
  "LAST_UPDATED_STAMP" TIMESTAMP
);
CREATE TABLE IF NOT EXISTS "SHIPMENT_ITEM" (
  "SHIPMENT_ID" VARCHAR(20) NOT NULL,
  "SHIPMENT_ITEM_SEQ_ID" VARCHAR(20) NOT NULL,
  "PRODUCT_ID" VARCHAR(20),
  "QUANTITY" TEXT,
  PRIMARY KEY ("SHIPMENT_ID", "SHIPMENT_ITEM_SEQ_ID")
);
SQL

echo "==> [3/3] seed + replica identity"
psql_file <<'SQL'
INSERT INTO "PRODUCT" ("PRODUCT_ID","PRODUCT_TYPE_ID","INTERNAL_NAME","PRODUCT_NAME")
  SELECT 'MP' || g, 'FINISHED_GOOD', 'Monolith Product ' || g, 'Product ' || g
  FROM generate_series(1, 50) g
ON CONFLICT ("PRODUCT_ID") DO NOTHING;
INSERT INTO "PRODUCT_CATEGORY" ("PRODUCT_CATEGORY_ID","CATEGORY_NAME")
  VALUES ('MCAT', 'Monolith Catalog')
ON CONFLICT ("PRODUCT_CATEGORY_ID") DO NOTHING;
INSERT INTO "PRODUCT_CATEGORY_MEMBER" ("PRODUCT_ID","PRODUCT_CATEGORY_ID","FROM_DATE")
  SELECT 'MP' || g, 'MCAT', '0' FROM generate_series(1, 50) g
ON CONFLICT ("PRODUCT_ID","PRODUCT_CATEGORY_ID") DO NOTHING;
INSERT INTO "PRODUCT_PRICE" ("PRODUCT_ID","PRODUCT_PRICE_TYPE_ID","CURRENCY_UOM_ID","FROM_DATE","PRICE")
  SELECT 'MP' || g, 'DEFAULT_PRICE', 'USD', '0', (10 + g) || '.00'
  FROM generate_series(1, 50) g
ON CONFLICT ("PRODUCT_ID","PRODUCT_PRICE_TYPE_ID","CURRENCY_UOM_ID","FROM_DATE") DO NOTHING;
INSERT INTO "SHIPMENT" ("SHIPMENT_ID","STATUS_ID")
  SELECT 'MSH' || g, 'SHIPMENT_INPUT' FROM generate_series(1, 20) g
ON CONFLICT ("SHIPMENT_ID") DO NOTHING;
INSERT INTO "SHIPMENT_ITEM" ("SHIPMENT_ID","SHIPMENT_ITEM_SEQ_ID","PRODUCT_ID","QUANTITY")
  SELECT 'MSH' || g, '00001', 'MP' || g, '2' FROM generate_series(1, 20) g
ON CONFLICT ("SHIPMENT_ID","SHIPMENT_ITEM_SEQ_ID") DO NOTHING;
ALTER TABLE "PRODUCT" REPLICA IDENTITY FULL;
ALTER TABLE "PRODUCT_CATEGORY" REPLICA IDENTITY FULL;
ALTER TABLE "PRODUCT_CATEGORY_MEMBER" REPLICA IDENTITY FULL;
ALTER TABLE "PRODUCT_PRICE" REPLICA IDENTITY FULL;
ALTER TABLE "PRODUCT_ASSOC" REPLICA IDENTITY FULL;
ALTER TABLE "SHIPMENT" REPLICA IDENTITY FULL;
ALTER TABLE "SHIPMENT_ITEM" REPLICA IDENTITY FULL;
SQL

echo "monolith product/shipment slices ready (50 products, 20 shipments seeded)"
